#!/usr/bin/env python3
"""Generate scripts/strings.sh, the shell half of the message catalog, from locales/strings.en.toml.

The shell scripts cannot read TOML and must not need Python, so the catalog entries they use are
written out as a plain bash file that they source. The file works with the bash 3.2 that macOS
ships (no associative arrays, no `${var,,}`): a `case` statement finds the text, and a small awk
program fills in the {placeholders}.

    python scripts/gen_strings.py          write scripts/strings.sh
    python scripts/gen_strings.py --check  exit 1 if scripts/strings.sh is out of date

Edit the catalog, then run this; never edit scripts/strings.sh by hand. tests/test_shell_strings.py
runs the check, so a stale file cannot be committed unnoticed.
"""
import argparse
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "locales" / "strings.en.toml"
OUTPUT = ROOT / "scripts" / "strings.sh"

# The catalog tables used by the shell scripts, one per script.
SHELL_TABLES = ("bootstrap", "cleanup", "prune")

HEADER = """\
# scripts/strings.sh - the shell half of the message catalog (locales/strings.en.toml).
#
# GENERATED by scripts/gen_strings.py. Do not edit it by hand: change the catalog and run
# `python scripts/gen_strings.py`. tests/test_shell_strings.py fails if this file is out of date.
#
# It is sourced by the scripts, and works with bash 3.2.
#
#   bites_text TABLE.KEY            set BITES_TEXT to the catalog text (status 1 if there is none)
#   bites_fmt TABLE.KEY [N=V ...]   print the text with each {N} replaced by V ({{ and }} are
#                                   literal braces, as in the catalog)

bites_text() {
  case "$1" in
"""

# The awk program avoids split(): the awk that macOS ships (the "one true awk") also splits a
# string at every newline when the separator is a single character, which cut off any value
# that contained a line break. index() and substr() behave the same in every awk.
FOOTER = """\
    *) return 1 ;;
  esac
}

bites_fmt() {
  local key="$1" packed="" pair
  shift
  bites_text "$key" || { printf 'bites: no message %s in the catalog\\n' "$key" >&2; return 1; }
  # The values travel to awk through the environment, joined by an SOH character, so that no
  # character in a value (a backslash, an ampersand, a brace, a newline) is ever interpreted.
  for pair in "$@"; do packed="$packed$pair"$'\\001'; done
  BITES_T="$BITES_TEXT" BITES_V="$packed" awk '
    BEGIN {
      t = ENVIRON["BITES_T"]
      v = ENVIRON["BITES_V"]
      while ((q = index(v, "\\001")) > 0) {
        pair = substr(v, 1, q - 1)
        v = substr(v, q + 1)
        p = index(pair, "=")
        if (p > 0) name[substr(pair, 1, p - 1)] = substr(pair, p + 1)
      }
      out = ""
      while (length(t) > 0) {
        c = substr(t, 1, 1)
        if (c == "{") {
          if (substr(t, 2, 1) == "{") { out = out "{"; t = substr(t, 3); continue }
          e = index(t, "}")
          nm = substr(t, 2, e - 2)
          if (e == 0 || !(nm in name)) { printf "bites: no value for {%s}\\n", nm > "/dev/stderr"; exit 2 }
          out = out name[nm]
          t = substr(t, e + 1)
        } else if (c == "}") {
          out = out "}"
          t = substr(t, (substr(t, 2, 1) == "}") ? 3 : 2)
        } else {
          m = match(t, /[{}]/)
          if (m == 0) { out = out t; t = "" } else { out = out substr(t, 1, m - 1); t = substr(t, m) }
        }
      }
      printf "%s", out
    }'
}
"""


ANNOTATIONS = '\n# Runner commands use stderr so command substitutions and formatted stdout stay intact.\n# The runner accepts commands on either stream. Keep human diagnostics separate.\nbites_annotate() {\n  local level="$1" title="$2" body="$3"\n  case "$level" in error|warning) ;; *) return 2 ;; esac\n  [ "${GITHUB_ACTIONS:-}" = true ] || return 0\n  title=${title//%/%25}; title=${title//$\'\\r\'/%0D}; title=${title//$\'\\n\'/%0A}\n  title=${title//:/%3A}; title=${title//,/%2C}\n  body=${body//%/%25}; body=${body//$\'\\r\'/%0D}; body=${body//$\'\\n\'/%0A}\n  printf \'::%s title=%s::%s\\n\' "$level" "$title" "$body" >&2\n}\n'

def quote(text: str) -> str:
    """Return `text` as one bash single-quoted word."""
    return "'" + text.replace("'", "'\\''") + "'"


def render() -> str:
    data = tomllib.loads(CATALOG.read_text(encoding="utf-8"))
    lines = [HEADER.rstrip("\n")]
    for table in SHELL_TABLES:
        for key, value in data[table].items():
            lines.append(f"    {table}.{key}) BITES_TEXT={quote(value)} ;;")
    return "\n".join(lines) + "\n" + FOOTER + ANNOTATIONS


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="only check that the file is up to date")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date: run python scripts/gen_strings.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
