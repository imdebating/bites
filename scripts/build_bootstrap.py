#!/usr/bin/env python3
"""Build the release copy of bootstrap.sh: one file that needs nothing next to it.

    python scripts/build_bootstrap.py [-o PATH] [--check-tag TAG]

scripts/bootstrap.sh finds scripts/strings.sh, templates/bites.yml and VERSION next to itself in a
checkout. The release copy has all three written into it, so that installing bites needs only
the download:

    curl -fsSLO https://github.com/imdebating/bites/releases/latest/download/bootstrap.sh
    bash bootstrap.sh OWNER/REPO main

It also runs when the script is piped into bash (`curl ... | bash -s -- OWNER/REPO main`).
The whole body is wrapped in a function that is called on the last line, so that bash has read
the entire script before anything runs, and a command that reads standard input (git, ssh)
cannot swallow the rest of it.

The output goes to PATH (default dist/bootstrap.sh) next to bootstrap.sh.sha256, which holds the
checksum in the format that `sha256sum -c` and `shasum -a 256 -c` read. The same input always
gives the same bytes. --check-tag stops the build unless TAG is `v` followed by the VERSION file.

scripts/bootstrap.sh marks what the build replaces with `# >>> release: NAME` and
`# <<< release: NAME` lines, for the names in BLOCKS below.
"""
import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BLOCKS = ("files", "version", "template check")
HEREDOC_END = "BITES_TEMPLATE_END"


def fail(message):
    print(f"build_bootstrap.py: {message}", file=sys.stderr)
    raise SystemExit(1)


def read_version(root):
    version = (root / "VERSION").read_text(encoding="utf-8").strip()
    if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", version):
        fail(f"VERSION must hold a number such as 1.6.0, not {version!r}")
    return version


def find_block(lines, name):
    """Return (start, end) line indexes of the marked block `name`, markers included."""
    start = [i for i, ln in enumerate(lines) if ln == f"# >>> release: {name}"]
    end = [i for i, ln in enumerate(lines) if ln == f"# <<< release: {name}"]
    if len(start) != 1 or len(end) != 1 or start[0] > end[0]:
        fail(f"scripts/bootstrap.sh needs exactly one '# >>> release: {name}' and one matching '# <<<' line")
    return start[0], end[0]


def build(root, version):
    """Return the text of the release script."""
    source = (root / "scripts" / "bootstrap.sh").read_text(encoding="utf-8")
    strings = (root / "scripts" / "strings.sh").read_text(encoding="utf-8")
    template = (root / "templates" / "bites.yml").read_text(encoding="utf-8")
    if not template.endswith("\n") or HEREDOC_END in template:
        fail("templates/bites.yml must end with a newline and must not contain " + HEREDOC_END)
    if "bites_fmt()" not in strings:
        fail("scripts/strings.sh does not define bites_fmt")

    lines = source.split("\n")
    replacement = {
        "files": [
            "# ---- scripts/strings.sh, written in by the release build ----",
            *strings.rstrip("\n").split("\n"),
            "# ---- templates/bites.yml, written in by the release build ----",
            "template_text() {",
            f"  cat <<'{HEREDOC_END}'",
            *template.rstrip("\n").split("\n"),
            HEREDOC_END,
            "}",
            "# ---- end of the files written in by the release build ----",
        ],
        "version": [f'VERSION="{version}"'],
        "template check": [],
    }
    spans = sorted((*find_block(lines, name), name) for name in BLOCKS)
    for (_, prev_end, _), (next_start, _, _) in zip(spans, spans[1:]):
        if prev_end >= next_start:
            fail("the release blocks in scripts/bootstrap.sh overlap")
    body = lines[:]
    for start, end, name in reversed(spans):
        body[start:end + 1] = replacement[name]

    shell_options = [i for i, ln in enumerate(body) if ln == "set -euo pipefail"]
    if len(shell_options) != 1:
        fail("scripts/bootstrap.sh needs exactly one 'set -euo pipefail' line")
    cut = shell_options[0] + 1
    if not body[0].startswith("#!"):
        fail("scripts/bootstrap.sh must start with a #! line")
    built = [
        body[0],
        f"# bootstrap.sh {version} - set up bites in a repository with one command.",
        "#",
        "# usage: bash bootstrap.sh [options] OWNER/REPO [BRANCH ...]",
        "#        bash bootstrap.sh [options] --all-branches OWNER/REPO",
        "#        bash bootstrap.sh --help     (lists every option)",
        "#",
        "# This is the release build of scripts/bootstrap.sh in https://github.com/imdebating/bites: one file,",
        "# with the message catalog and the workflow template written into it. It was generated by",
        "# scripts/build_bootstrap.py, so change scripts/bootstrap.sh and not this file. The checksum is in",
        "# bootstrap.sh.sha256 next to it in the release.",
        "set -euo pipefail",
        "",
        "main() {",
        *body[cut:],
        "}",
        'main "$@"; exit $?',
        "",
    ]
    text = "\n".join(built)
    leftovers = (r"@@VERSION@@", r"BASH_SOURCE", r"(?m)^HERE=", r"\$\{?HERE\b", r"# >>> release", r"# <<< release")
    for pattern in leftovers:
        if re.search(pattern, text):
            fail(f"the release script still contains something only a checkout can use: {pattern}")
    return text


def check_syntax(path):
    result = subprocess.run(["bash", "-n", str(path)], capture_output=True, text=True)
    if result.returncode != 0:
        fail("bash -n rejects the release script:\n" + result.stderr)


def main(argv=None):
    parser = argparse.ArgumentParser(description="Build the one-file release copy of bootstrap.sh.")
    parser.add_argument("-o", "--output", default=str(ROOT / "dist" / "bootstrap.sh"))
    parser.add_argument("--check-tag", metavar="TAG", help="stop unless TAG is v followed by the VERSION file")
    args = parser.parse_args(argv)

    version = read_version(ROOT)
    if args.check_tag is not None and args.check_tag != f"v{version}":
        fail(f"the tag {args.check_tag!r} does not match the VERSION file (expected 'v{version}')")
    text = build(ROOT, version)

    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8", newline="\n")
    out.chmod(0o755)
    check_syntax(out)
    digest = hashlib.sha256(out.read_bytes()).hexdigest()
    Path(str(out) + ".sha256").write_text(f"{digest}  {out.name}\n", encoding="utf-8")
    print(f"{out} ({version}, sha256 {digest})")


if __name__ == "__main__":
    main()
